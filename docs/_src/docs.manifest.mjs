/* The per-repo front door. Generated by build-index-page.mjs, stamped like
   any document, but NOT indexed for search — its "map" is just links to the
   real documents, which are themselves indexed. Kept separate from DOCS so
   build-index.mjs never has to special-case it. */
export const INDEX_PAGES = REPOS.map((r) => ({
  id: `${r.id}-index`,
  repo: r.id,
  file: "docs/index.html",
  title: "Documentation",
  role: null,
  blurb: "",
  components: [],
}));

/* Everything stamp.mjs writes into: the six documents plus the two front
   doors. build-index.mjs uses DOCS only. */
export const STAMP_TARGETS = DOCS.concat(INDEX_PAGES);

export const docById = (id) => STAMP_TARGETS.find((d) => d.id === id);
export const repoById = (id) => REPOS.find((r) => r.id === id);

/** Absolute path to a document on disk. */
export const docPath = (doc) => resolve(repoById(doc.repo).root, doc.file);

/**
 * Href from one document to another. Same repo → bare filename, since every
 * document lives in docs/. Across repos → a sibling-checkout hop, which is
 * the only arrangement in which cross-repo links can resolve at all.
 */
export function hrefBetween(from, to) {
  const file = to.file.replace(/^docs\//, "");
  if (from.repo === to.repo) return file;
  // Both checkouts sit as siblings under one parent, so the hop out of
  // <repo>/docs/ and into the other repo's is symmetric: up two, across one.
  // The directory name is read from the repo root above rather than written
  // out here, so a rename needs the one path at the top of this file changed
  // and nothing else. The previous hardcoded pair outlived two renames and
  // pointed nine links at folders that no longer existed.
  return `../../${basename(repoById(to.repo).root)}/docs/${file}`;
}
