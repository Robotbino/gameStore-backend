/* ═══════════════════════════════════════════════════════════════════════════
   docs.manifest.mjs — the one description of the documentation set
   ═══════════════════════════════════════════════════════════════════════════

   Every generated thing reads this file: the cross-document nav, the search
   index, and which component stylesheets each document gets stamped with.

   This exists because the nav used to be hand-written into all six documents
   and had rotted in both directions at once — the backend docs pointed at
   ../../../GameStore/ (wrong depth AND wrong case) and the frontend docs at
   ../../GameStoreBackEnd/Bino/, a folder name from before the repo was
   renamed. Nine dead links, none of which any single edit would have caught.
   Now a link is wrong in one place or not at all.

   ── Adding a document ────────────────────────────────────────────────────
   Add an entry below, give the HTML file the four marker pairs (see
   stamp.mjs), and run:

     node docs/_src/stamp.mjs

   ── A note on `root` ─────────────────────────────────────────────────────
   The two repos are assumed to sit as siblings under one parent directory.
   That assumption is ONLY made here, at build time, by scripts you run by
   hand. The documents the scripts produce never reach across the boundary —
   that is the whole point of stamping them self-contained.
   ═══════════════════════════════════════════════════════════════════════════ */

