/* ═══════════════════════════════════════════════════════════════════════════
   vendor.mjs — fetch the third-party assets the docs need to work offline
   ═══════════════════════════════════════════════════════════════════════════

   The six documents used to pull Mermaid and Atkinson/JetBrains from CDNs,
   which meant "open the file from disk with no network" produced a serif
   fallback and no diagrams. This script pulls both into docs/vendor/ in BOTH
   repos so every document is genuinely self-sufficient.

   Run it once, and again only when you want to move Mermaid's version:

     node docs/_src/vendor.mjs

   Fonts are subset to latin + latin-ext. The wider Google subsets (cyrillic,
   greek, vietnamese) are ~12 extra files for glyphs no document contains.
   Note that the latin range already covers U+2191, which is the ↑ in the
   back-to-top button — that one is load-bearing.

   Output is written to docs/vendor/ and is meant to be committed: the whole
   point is that a fresh clone works offline without running anything.
   ═══════════════════════════════════════════════════════════════════════════ */

import { mkdir, writeFile, readFile, stat } from "node:fs/promises";
import { join } from "node:path";
import { REPOS } from "./docs.manifest.mjs";

const MERMAID = "https://cdn.jsdelivr.net/npm/mermaid@11/dist/mermaid.min.js";
const GF = "https://fonts.googleapis.com/css2?family=Atkinson+Hyperlegible:ital,wght@0,400;0,700;1,400;1,700&family=JetBrains+Mono:wght@400;500;600&display=swap";

// Google serves woff2 only to browser-ish UAs; anything else gets ttf.
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

const KEEP_SUBSETS = new Set(["latin", "latin-ext"]);

const kb = (n) => `${(n / 1024).toFixed(0)} KB`;

async function get(url, headers = {}) {
  const res = await fetch(url, { headers });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return res;
}

/* ── Fonts ────────────────────────────────────────────────────────────────
   Parse the @font-face blocks Google returns, keep the latin ones, download
   each woff2, and rewrite src: to a local path. The unicode-range lines are
   preserved exactly — they are what lets the browser skip a file it doesn't
   need for the glyphs on screen. */
async function fonts() {
  const css = await (await get(GF, { "User-Agent": UA })).text();

  const blocks = [...css.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)];
  const files = [];
  const out = [];

  for (const [, subset, block] of blocks) {
    if (!KEEP_SUBSETS.has(subset)) continue;

    const fam = block.match(/font-family:\s*'([^']+)'/)?.[1] ?? "";
    const style = block.match(/font-style:\s*(\w+)/)?.[1] ?? "normal";
    const weight = block.match(/font-weight:\s*(\d+)/)?.[1] ?? "400";
    const url = block.match(/url\((https:[^)]+\.woff2)\)/)?.[1];
    if (!url) continue;

    const slug = fam.toLowerCase().replace(/\s+/g, "-");
    const name = `${slug}-${weight}${style === "italic" ? "i" : ""}-${subset}.woff2`;

    files.push({ url, name });
    out.push(block.replace(/url\(https:[^)]+\.woff2\)/, `url("fonts/${name}")`).trim());
  }

  const bytes = new Map();
  for (const f of files) {
    bytes.set(f.name, Buffer.from(await (await get(f.url, { "User-Agent": UA })).arrayBuffer()));
  }

  const total = [...bytes.values()].reduce((a, b) => a + b.length, 0);
  console.log(`fonts    ${files.length} woff2, ${kb(total)} total`);
  return { faces: out.join("\n"), bytes };
}

/* ── Mermaid ──────────────────────────────────────────────────────────── */
async function mermaid() {
  const buf = Buffer.from(await (await get(MERMAID)).arrayBuffer());
  console.log(`mermaid  ${kb(buf.length)}  (${MERMAID})`);
  return buf;
}

/* ── Write into both repos ────────────────────────────────────────────── */
const [f, m] = await Promise.all([fonts(), mermaid()]);

for (const repo of REPOS) {
  const vendor = join(repo.root, "docs", "vendor");
  await mkdir(join(vendor, "fonts"), { recursive: true });
  await writeFile(join(vendor, "mermaid.min.js"), m);
  for (const [name, buf] of f.bytes) await writeFile(join(vendor, "fonts", name), buf);
  console.log(`  -> ${vendor}`);
}

// The @font-face block is stamped into core.css rather than kept by hand, so
// re-running this after a font change cannot leave the two out of step.
const facesPath = new URL("./fonts.generated.css", import.meta.url);
await writeFile(
  facesPath,
  `/* Generated by vendor.mjs — do not edit. Paths are relative to the document,
   which is why they read "fonts/..." and not "vendor/fonts/...": core.css is
   inlined INTO the document, so url() resolves against the HTML file. */\n\n` +
    f.faces.replace(/url\("fonts\//g, 'url("vendor/fonts/') + "\n"
);
console.log(`\nwrote ${facesPath.pathname.split("/").pop()} (${f.faces.split("@font-face").length - 1} faces)`);
